// Writes app/[lang]/…/page.tsx for every Portuguese page in app/(pt), so each page also exists under /en, /es and /fr.
// Each file only re-exports its Portuguese twin, which reads the language from the address.
// Run after adding a page: node scripts/lang-pages.mjs (a test fails when a twin is missing or out of date).
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "app");
const pt = join(root, "(pt)");
const other = join(root, "[lang]");

/** Only in Portuguese: the personal area and the legal texts (see lib/i18n/config.ts). */
export const portugueseOnly = ["conta", "patinhas", "privacidade", "cookies"];

const walk = (dir) => readdirSync(dir).flatMap((n) => (statSync(join(dir, n)).isDirectory() ? walk(join(dir, n)) : [join(dir, n)]));

/** The re-export file for one Portuguese page, or null when the page stays Portuguese only. */
export function twinOf(file) {
  const rel = relative(pt, file).split("\\").join("/");
  if (!/(^|\/)(page|not-found|error|loading)\.tsx$/.test(rel) || rel === "layout.tsx") return null;
  if (portugueseOnly.some((p) => rel === p || rel.startsWith(`${p}/`))) return null;
  const src = readFileSync(file, "utf8");
  const names = ["default"];
  for (const name of ["generateMetadata", "generateStaticParams"]) if (new RegExp(`export (async )?function ${name}\\b`).test(src)) names.push(name);
  // Route settings must be written in the file itself for Next.js to read them.
  const settings = [...src.matchAll(/^export const (revalidate|dynamic|dynamicParams) = .*;$/gm)].map((m) => m[0]);
  // app/[lang]/layout.tsx allows only its three languages; pages for cats, news and articles added after the build still open.
  if (rel.includes("[") && !settings.some((s) => s.includes("dynamicParams"))) settings.push("export const dynamicParams = true;");
  const client = src.startsWith('"use client"') ? '"use client";\n' : "";
  const from = `@/app/(pt)/${rel.replace(/\.tsx$/, "")}`;
  const body = `${client}// Generated by scripts/lang-pages.mjs: the same page as app/(pt)/${rel}, under /en, /es and /fr.\nexport { ${names.join(", ")} } from "${from}";\n${settings.map((s) => `${s}\n`).join("")}`;
  return { path: join(other, rel), body };
}

export function twins() {
  return walk(pt).map(twinOf).filter(Boolean);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const f of walk(other)) if (!f.endsWith("layout.tsx")) rmSync(f);
  for (const { path, body } of twins()) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, body);
  }
  console.log(`Wrote ${twins().length} pages in app/[lang]`);
}
